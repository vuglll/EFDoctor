using System.Collections.Immutable;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Diagnostics;
using Microsoft.CodeAnalysis.Operations;

namespace EFDoctor.Analyzers;

[DiagnosticAnalyzer(LanguageNames.CSharp)]
public sealed class UnsizedSnapshotColumnAnalyzer : DiagnosticAnalyzer
{
    public const string DiagnosticId = "EFD035";
    public const string RuleTitle = "Unsized column in the model snapshot";
    public const string DocumentationKey = "EFD035";
    public const string IndexedStringImpact = "SQL Server cannot use an nvarchar(max) or varchar(max) column as an index key, so the migration that creates this index or key fails when it is applied.";
    public const string IndexedStringRemediation = "Give the string a maximum length with HasMaxLength or [MaxLength] (an index key on SQL Server can be at most 1700 bytes, so 850 characters for nvarchar), then generate a migration. If the column must be unbounded, index a computed hash or prefix column instead.";
    public const string DecimalImpact = "EF Core found no precision for this decimal and fell back to SQL Server's decimal(18,2), so values with more than two decimal places, such as rates or percentages, are silently rounded when saved.";
    public const string DecimalRemediation = "Configure the precision the values need with HasPrecision(precision, scale) or [Precision(precision, scale)], then generate a migration. If decimal(18,2) is intended and configured with HasColumnType elsewhere, suppress EFD035 with a recorded reason.";

    private const string ModelSnapshotMetadataName = "Microsoft.EntityFrameworkCore.Infrastructure.ModelSnapshot";
    private const string Message = "{0}";

    public static readonly DiagnosticDescriptor Rule = new(
        DiagnosticId,
        RuleTitle,
        Message,
        "Correctness",
        DiagnosticSeverity.Warning,
        isEnabledByDefault: true,
        description: "Reports an nvarchar(max) or varchar(max) column used in an index or key, and a decimal column left at the default decimal(18,2), in an EF Core model snapshot.",
        helpLinkUri: EfHelpLinks.For(DiagnosticId));

    public override ImmutableArray<DiagnosticDescriptor> SupportedDiagnostics => ImmutableArray.Create(Rule);

    public override void Initialize(AnalysisContext context)
    {
        // EF Core generates model snapshots with an `// <auto-generated />` header, and they are the
        // only code this rule reads.
        context.ConfigureGeneratedCodeAnalysis(GeneratedCodeAnalysisFlags.Analyze | GeneratedCodeAnalysisFlags.ReportDiagnostics);
        context.EnableConcurrentExecution();
        context.RegisterCompilationStartAction(StartCompilation);
    }

    private static void StartCompilation(CompilationStartAnalysisContext context)
    {
        if (!EfAnalysisScope.Includes(context.Options, context.Compilation))
        {
            return;
        }

        var modelSnapshot = context.Compilation.GetTypeByMetadataName(ModelSnapshotMetadataName);
        if (modelSnapshot is null)
        {
            return;
        }

        context.RegisterOperationBlockAction(blockContext =>
        {
            if (blockContext.OwningSymbol is not IMethodSymbol method || !MissingForeignKeyIndexAnalyzer.IsSnapshotBuildModel(method, modelSnapshot))
            {
                return;
            }

            var collector = new MissingForeignKeyIndexAnalyzer.SnapshotCollector();
            foreach (var block in blockContext.OperationBlocks)
            {
                collector.Visit(block);
            }

            foreach (var property in blockContext.OperationBlocks.SelectMany(static block => block.Descendants()).OfType<IInvocationOperation>())
            {
                if (TryReadProperty(property, out var column))
                {
                    Analyze(blockContext, column, collector.Entities, method.ContainingType.Name);
                }
            }
        });
    }

    private static void Analyze(
        OperationBlockAnalysisContext context,
        Column column,
        IReadOnlyDictionary<string, MissingForeignKeyIndexAnalyzer.EntityRecord> entities,
        string snapshotName)
    {
        var shortEntity = column.Entity.Substring(column.Entity.LastIndexOf('.') + 1);
        var storeType = column.ColumnType?.Trim().ToLowerInvariant();
        if (storeType is "nvarchar(max)" or "varchar(max)"
            && entities.TryGetValue(column.Entity, out var entity)
            && entity.CoveringPropertySets.Any(set => set.Contains(column.Name)))
        {
            Report(
                context,
                column,
                "high",
                $"'{shortEntity}.{column.Name}' is {storeType}, which SQL Server cannot use in an index or key",
                $"Model snapshot '{snapshotName}' maps '{column.Entity}.{column.Name}' as '{column.ColumnType}', and the same entity declares an index or key that includes '{column.Name}'.",
                IndexedStringImpact,
                IndexedStringRemediation);
            return;
        }

        if (column.ClrType == "decimal"
            && storeType == "decimal(18,2)"
            && !column.HasPrecision
            && !HasPrecisionAttribute(context.Compilation, column))
        {
            Report(
                context,
                column,
                "advisory",
                $"'{shortEntity}.{column.Name}' has no configured precision, so SQL Server stores it as decimal(18,2)",
                $"Model snapshot '{snapshotName}' maps decimal '{column.Entity}.{column.Name}' as 'decimal(18,2)', the SQL Server default, with no HasPrecision, and its CLR property has no [Precision] or [Column(TypeName)] attribute.",
                DecimalImpact,
                DecimalRemediation);
        }
    }

    private static void Report(OperationBlockAnalysisContext context, Column column, string confidence, string message, string evidence, string impact, string remediation)
    {
        var properties = ImmutableDictionary<string, string?>.Empty
            .Add(DiagnosticPropertyNames.Confidence, confidence)
            .Add(DiagnosticPropertyNames.Evidence, evidence)
            .Add(DiagnosticPropertyNames.LikelyImpact, impact)
            .Add(DiagnosticPropertyNames.SuggestedRemediation, remediation)
            .Add(DiagnosticPropertyNames.DocumentationReference, DocumentationKey);

        context.ReportDiagnostic(EfDiagnostic.Create(Rule, column.Chain.Syntax.GetLocation(), properties, message));
    }

    // `b.Property<T>("Name")` followed by its fluent configuration calls, as the snapshot generator
    // writes them: `.HasMaxLength(…)`, `.HasPrecision(…)`, `.HasColumnType("…")`.
    private static bool TryReadProperty(IInvocationOperation property, out Column column)
    {
        column = null!;
        if (property.TargetMethod.Name != "Property"
            || property.TargetMethod.TypeArguments.Length != 1
            || property.Arguments.FirstOrDefault()?.Value.ConstantValue is not { HasValue: true, Value: string name }
            || !MissingForeignKeyIndexAnalyzer.TryGetContainingEntity(property, out var entity))
        {
            return false;
        }

        string? columnType = null;
        var hasPrecision = false;
        IOperation chain = property;
        while (NextInChain(chain) is { } next)
        {
            switch (next.TargetMethod.Name)
            {
                case "HasColumnType" when next.Arguments.LastOrDefault()?.Value.ConstantValue is { HasValue: true, Value: string type }:
                    columnType = type;
                    break;
                case "HasPrecision":
                    hasPrecision = true;
                    break;
            }

            chain = next;
        }

        var clrType = property.TargetMethod.TypeArguments[0];
        if (clrType is INamedTypeSymbol { OriginalDefinition.SpecialType: SpecialType.System_Nullable_T } nullable)
        {
            clrType = nullable.TypeArguments[0];
        }

        column = new Column(entity, name, clrType.SpecialType == SpecialType.System_Decimal ? "decimal" : clrType.Name, columnType, hasPrecision, (IInvocationOperation)chain);
        return true;
    }

    private static IInvocationOperation? NextInChain(IOperation current)
    {
        var parent = current.Parent;
        while (parent is IConversionOperation)
        {
            current = parent;
            parent = parent.Parent;
        }

        return parent switch
        {
            IInvocationOperation instanceCall when ReferenceEquals(instanceCall.Instance, current) => instanceCall,
            IArgumentOperation { Parameter.Ordinal: 0, Parent: IInvocationOperation extensionCall } when extensionCall.TargetMethod.IsExtensionMethod || extensionCall.TargetMethod.IsStatic => extensionCall,
            _ => null,
        };
    }

    private static bool HasPrecisionAttribute(Compilation compilation, Column column)
    {
        var type = compilation.GetTypeByMetadataName(column.Entity);
        for (var current = type; current is not null; current = current.BaseType)
        {
            foreach (var property in current.GetMembers(column.Name).OfType<IPropertySymbol>())
            {
                if (property.GetAttributes().Any(static attribute =>
                    attribute.AttributeClass?.Name == "PrecisionAttribute"
                    || (attribute.AttributeClass?.Name == "ColumnAttribute"
                        && attribute.NamedArguments.Any(static argument => argument.Key == "TypeName" && argument.Value.Value is string))))
                {
                    return true;
                }
            }
        }

        return false;
    }

    private sealed class Column
    {
        public Column(string entity, string name, string clrType, string? columnType, bool hasPrecision, IInvocationOperation chain)
        {
            Entity = entity;
            Name = name;
            ClrType = clrType;
            ColumnType = columnType;
            HasPrecision = hasPrecision;
            Chain = chain;
        }

        public string Entity { get; }

        public string Name { get; }

        public string ClrType { get; }

        public string? ColumnType { get; }

        public bool HasPrecision { get; }

        public IInvocationOperation Chain { get; }
    }
}
