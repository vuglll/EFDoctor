using System.Collections.Concurrent;
using System.Collections.Immutable;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Diagnostics;
using Microsoft.CodeAnalysis.Operations;

namespace EFDoctor.Analyzers;

[DiagnosticAnalyzer(LanguageNames.CSharp)]
public sealed class UnindexedPredicateColumnAnalyzer : DiagnosticAnalyzer
{
    public const string DiagnosticId = "EFD036";
    public const string RuleTitle = "Query filter on a column without an index";
    public const string Confidence = "advisory";
    public const string DocumentationKey = "EFD036";
    public const string Impact = "No index in the model snapshot leads with any column this query filters on, so the database may have to scan the table to find matching rows. The cost grows with the table and depends on how selective the filter is; on a small table, or a low-selectivity column, a scan can be the better plan.";
    public const string Remediation = "Check the query plan for a scan. If one of the filter columns is selective, add HasIndex for it (or an [Index] attribute), generate a migration, and review the SQL. Suppress EFD036 for small tables, low-selectivity columns, or indexes managed outside EF migrations, with a recorded reason.";

    private const string ModelSnapshotMetadataName = "Microsoft.EntityFrameworkCore.Infrastructure.ModelSnapshot";
    private const string Message = "No index in the model snapshot leads with '{0}.{1}', which this query filters on";

    public static readonly DiagnosticDescriptor Rule = new(
        DiagnosticId,
        RuleTitle,
        Message,
        "Performance",
        DiagnosticSeverity.Info,
        isEnabledByDefault: true,
        description: "Reports an EF Core query predicate whose filter columns are not the leading column of any index or key that the model snapshot of the same compilation maps for the entity.",
        helpLinkUri: EfHelpLinks.For(DiagnosticId),
        customTags: WellKnownDiagnosticTags.CompilationEnd);

    public override ImmutableArray<DiagnosticDescriptor> SupportedDiagnostics => ImmutableArray.Create(Rule);

    public override void Initialize(AnalysisContext context)
    {
        // Model snapshots are generated (`// <auto-generated />`), so generated code is analyzed to read
        // their indexes. Predicates in generated code are skipped below, and nothing is reported there.
        context.ConfigureGeneratedCodeAnalysis(GeneratedCodeAnalysisFlags.Analyze);
        context.EnableConcurrentExecution();
        context.RegisterCompilationStartAction(StartCompilation);
    }

    private static void StartCompilation(CompilationStartAnalysisContext context)
    {
        if (!EfAnalysisScope.Includes(context.Options, context.Compilation))
        {
            return;
        }

        var modelSnapshot = context.Compilation.GetTypeByMetadataName(ModelSnapshotMetadataName);
        var scan = EfPredicateScan.Create(context.Compilation, followComposedLocals: true);
        if (modelSnapshot is null || scan is null)
        {
            return;
        }

        var snapshots = new ConcurrentBag<(string Name, IReadOnlyDictionary<string, MissingForeignKeyIndexAnalyzer.EntityRecord> Entities)>();
        var candidates = new ConcurrentBag<Candidate>();

        context.RegisterOperationBlockAction(blockContext =>
        {
            if (blockContext.OwningSymbol is not IMethodSymbol method || !MissingForeignKeyIndexAnalyzer.IsSnapshotBuildModel(method, modelSnapshot))
            {
                return;
            }

            var collector = new MissingForeignKeyIndexAnalyzer.SnapshotCollector();
            foreach (var block in blockContext.OperationBlocks)
            {
                collector.Visit(block);
            }

            snapshots.Add((method.ContainingType.Name, collector.Entities));
        });

        context.RegisterOperationAction(
            operationContext =>
            {
                if (!operationContext.IsGeneratedCode
                    && scan.TryGetPredicate((IInvocationOperation)operationContext.Operation, out var predicate)
                    && EfQueryOperationAnalysis.GetLambdaExpression(predicate.Lambda) is { } body)
                {
                    var columns = new List<IPropertyReferenceOperation>();
                    CollectFilterColumns(body, predicate.Parameter, columns);
                    if (columns.Count > 0)
                    {
                        candidates.Add(new Candidate(predicate.Origin.Syntax, predicate.Parameter.Type, columns));
                    }
                }
            },
            OperationKind.Invocation);

        context.RegisterCompilationEndAction(endContext =>
        {
            // The filters of one query combine: `Where(o => o.CustomerId == id).Where(o => o.Open)`
            // can seek the CustomerId index. Predicates traced to the same origin are one query,
            // judged on all their columns, and reported once, at the first predicate's column.
            var queries = candidates
                .GroupBy(static candidate => (candidate.Origin, candidate.Entity), QueryKeyComparer.Instance)
                .Select(static group =>
                {
                    var ordered = group.OrderBy(static candidate => candidate.Columns[0].Syntax.SpanStart).ToList();
                    return new Candidate(ordered[0].Origin, ordered[0].Entity, ordered.SelectMany(static candidate => candidate.Columns).ToList());
                });
            foreach (var candidate in queries)
            {
                var entityName = candidate.Entity.ToDisplayString(SymbolDisplayFormat.CSharpErrorMessageFormat);
                foreach (var (snapshotName, entities) in snapshots)
                {
                    if (!TryGetLeadingColumns(entityName, entities, out var leading))
                    {
                        continue;
                    }

                    if (candidate.Columns.Any(column => leading.Contains(column.Property.Name)))
                    {
                        break;
                    }

                    var first = candidate.Columns[0];
                    var filters = string.Join(", ", candidate.Columns.Select(static column => column.Property.Name).Distinct(StringComparer.Ordinal));
                    var indexed = leading.Count == 0 ? "none" : string.Join(", ", leading.OrderBy(static name => name, StringComparer.Ordinal));
                    var properties = ImmutableDictionary<string, string?>.Empty
                        .Add(DiagnosticPropertyNames.Confidence, Confidence)
                        .Add(DiagnosticPropertyNames.Evidence, $"The predicate filters '{candidate.Entity.Name}' on [{filters}]. Model snapshot '{snapshotName}' maps '{entityName}' with indexes and keys leading with [{indexed}], so no filter column leads an index.")
                        .Add(DiagnosticPropertyNames.LikelyImpact, Impact)
                        .Add(DiagnosticPropertyNames.SuggestedRemediation, Remediation)
                        .Add(DiagnosticPropertyNames.DocumentationReference, DocumentationKey);

                    endContext.ReportDiagnostic(EfDiagnostic.Create(Rule, first.Syntax.GetLocation(), properties, candidate.Entity.Name, first.Property.Name));
                    break;
                }
            }
        });
    }

    // The leading columns of every index and key of the entity and its base types, when the
    // snapshot maps the entity and its coverage is conclusive.
    private static bool TryGetLeadingColumns(string entityName, IReadOnlyDictionary<string, MissingForeignKeyIndexAnalyzer.EntityRecord> entities, out HashSet<string> leading)
    {
        leading = new HashSet<string>(StringComparer.Ordinal);
        var visited = new HashSet<string>(StringComparer.Ordinal);
        for (var name = entityName; name is not null; )
        {
            if (!visited.Add(name) || !entities.TryGetValue(name, out var entity) || entity.IsCoverageInconclusive)
            {
                return false;
            }

            foreach (var set in entity.CoveringPropertySets)
            {
                leading.Add(set[0]);
            }

            name = entity.BaseEntityName;
        }

        return true;
    }

    // The columns of the top-level `&&` terms that an index could seek: equality, range, prefix,
    // and collection membership on a property read directly from the entity parameter.
    private static void CollectFilterColumns(IOperation expression, IParameterSymbol entity, List<IPropertyReferenceOperation> columns)
    {
        expression = EfQueryOperationAnalysis.Unwrap(expression);
        switch (expression)
        {
            case IBinaryOperation { OperatorKind: BinaryOperatorKind.ConditionalAnd, OperatorMethod: null } conjunction:
                CollectFilterColumns(conjunction.LeftOperand, entity, columns);
                CollectFilterColumns(conjunction.RightOperand, entity, columns);
                return;
            case IBinaryOperation
            {
                OperatorKind: BinaryOperatorKind.Equals or BinaryOperatorKind.LessThan or BinaryOperatorKind.LessThanOrEqual
                    or BinaryOperatorKind.GreaterThan or BinaryOperatorKind.GreaterThanOrEqual,
            } comparison:
                if (TryGetColumn(comparison.LeftOperand, entity, out var left) && !ReadsParameter(comparison.RightOperand, entity))
                {
                    columns.Add(left);
                }
                else if (TryGetColumn(comparison.RightOperand, entity, out var right) && !ReadsParameter(comparison.LeftOperand, entity))
                {
                    columns.Add(right);
                }

                return;
            case IInvocationOperation { TargetMethod.Name: "StartsWith", Instance: { } instance } startsWith
                when startsWith.TargetMethod.ContainingType.SpecialType == SpecialType.System_String
                    && TryGetColumn(instance, entity, out var prefixColumn)
                    && startsWith.Arguments.All(argument => !ReadsParameter(argument.Value, entity)):
                columns.Add(prefixColumn);
                return;
            case IInvocationOperation { TargetMethod.Name: "Contains" } contains:
                var source = EfQueryOperationAnalysis.GetInvocationSource(contains);
                var value = contains.Instance is not null
                    ? contains.Arguments.FirstOrDefault()?.Value
                    : contains.Arguments.FirstOrDefault(static argument => argument.Parameter?.Ordinal == 1)?.Value;
                if (source is not null
                    && EfQueryOperationAnalysis.Unwrap(source) is ILocalReferenceOperation or IParameterReferenceOperation or IFieldReferenceOperation
                    && source.Type?.SpecialType != SpecialType.System_String
                    && !ReadsParameter(source, entity)
                    && value is not null
                    && TryGetColumn(value, entity, out var memberColumn))
                {
                    columns.Add(memberColumn);
                }

                return;
        }
    }

    private static bool TryGetColumn(IOperation operation, IParameterSymbol entity, out IPropertyReferenceOperation column)
    {
        column = null!;
        operation = EfQueryOperationAnalysis.Unwrap(operation);
        if (operation is not IPropertyReferenceOperation { Instance: { } instance, Property: { IsStatic: false } property } reference
            || EfQueryOperationAnalysis.Unwrap(instance) is not IParameterReferenceOperation parameter
            || !SymbolEqualityComparer.Default.Equals(parameter.Parameter, entity)
            || !EfQueryOperationAnalysis.IsSimpleMappedProperty(property)
            || UnwrapNullable(property.Type).SpecialType == SpecialType.System_Boolean)
        {
            return false;
        }

        column = reference;
        return true;
    }

    private static ITypeSymbol UnwrapNullable(ITypeSymbol type) =>
        type is INamedTypeSymbol { OriginalDefinition.SpecialType: SpecialType.System_Nullable_T } nullable ? nullable.TypeArguments[0] : type;

    private static bool ReadsParameter(IOperation operation, IParameterSymbol entity) =>
        operation.DescendantsAndSelf().Any(candidate =>
            candidate is IParameterReferenceOperation reference && SymbolEqualityComparer.Default.Equals(reference.Parameter, entity));

    private sealed class Candidate
    {
        public Candidate(SyntaxNode origin, ITypeSymbol entity, List<IPropertyReferenceOperation> columns)
        {
            Origin = origin;
            Entity = entity;
            Columns = columns;
        }

        public SyntaxNode Origin { get; }

        public ITypeSymbol Entity { get; }

        public List<IPropertyReferenceOperation> Columns { get; }
    }

    private sealed class QueryKeyComparer : IEqualityComparer<(SyntaxNode Origin, ITypeSymbol Entity)>
    {
        public static readonly QueryKeyComparer Instance = new();

        public bool Equals((SyntaxNode Origin, ITypeSymbol Entity) x, (SyntaxNode Origin, ITypeSymbol Entity) y) =>
            x.Origin == y.Origin && SymbolEqualityComparer.Default.Equals(x.Entity, y.Entity);

        public int GetHashCode((SyntaxNode Origin, ITypeSymbol Entity) key) =>
            key.Origin.GetHashCode() * 31 + SymbolEqualityComparer.Default.GetHashCode(key.Entity);
    }
}
