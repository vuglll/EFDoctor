        sealed class TestContext : DbContext
        {
        }

        {{additionalTypes}}

        static class Subject
        {
            {{member}}

            private static async IAsyncEnumerable<int> Stream()
            {
                await Task.Yield();
                yield return 1;
            }
        }
        """;

    public static string SnapshotSource(string body, string additionalTypes = "", bool generated = true) => $$"""
        {{(generated ? "// <auto-generated />" : string.Empty)}}
        using System;
        using System.Diagnostics.CodeAnalysis;
        using Microsoft.EntityFrameworkCore;
        using Microsoft.EntityFrameworkCore.Infrastructure;

        sealed class TestContext : DbContext
        {
        }

        {{additionalTypes}}

        sealed class TestSnapshot : ModelSnapshot
        {
            protected override void BuildModel(ModelBuilder modelBuilder)
            {
                {{body}}
            }
        }
        """;

    // The test host's own assemblies include the test framework, and a compilation that references
    // one is a test project, which the analyzers skip. Fixtures stand for production code.
    private static IEnumerable<MetadataReference> TrustedPlatformReferences(bool includeTestFramework)
    {
        var paths = ((string?)AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES"))?
            .Split(Path.PathSeparator, StringSplitOptions.RemoveEmptyEntries)
            ?? throw new InvalidOperationException("Trusted platform assemblies are unavailable.");
        return paths
            .Where(static path => !OptionalProviderAssemblyNames.Contains(Path.GetFileName(path)))
            .Where(path => includeTestFramework || !IsTestFrameworkAssembly(Path.GetFileNameWithoutExtension(path)))
            .Select(static path => MetadataReference.CreateFromFile(path));
    }

    private static bool IsTestFrameworkAssembly(string name) =>
        name.StartsWith("xunit", StringComparison.OrdinalIgnoreCase)
        || name.StartsWith("Microsoft.VisualStudio.TestPlatform", StringComparison.OrdinalIgnoreCase)
        || name.StartsWith("Microsoft.TestPlatform", StringComparison.OrdinalIgnoreCase)
        || name.StartsWith("testhost", StringComparison.OrdinalIgnoreCase);

    private sealed class GlobalOptionsProvider(IReadOnlyDictionary<string, string>? values) : AnalyzerConfigOptionsProvider
    {
        public override AnalyzerConfigOptions GlobalOptions { get; } = new Options(values);

        public override AnalyzerConfigOptions GetOptions(SyntaxTree tree) => new Options(null);

        public override AnalyzerConfigOptions GetOptions(AdditionalText textFile) => new Options(null);

        private sealed class Options(IReadOnlyDictionary<string, string>? values) : AnalyzerConfigOptions
        {
            public override bool TryGetValue(string key, out string value)
            {
                value = string.Empty;
                return values is not null && values.TryGetValue(key, out value!);
            }
        }
    }

    internal static CSharpCompilation CreateCompilation(
        string source,
        bool includeEntityFramework,
        bool includeRelational,
        bool includeSqlServer,
        bool includeNpgsql,
        bool includeMySql,
        ReportDiagnostic? configuredSeverity,
        string diagnosticId,
        bool includeTestFramework = false)
    {
        var syntaxTree = CSharpSyntaxTree.ParseText(
            source,
            new CSharpParseOptions(LanguageVersion.Preview),
            path: "/tests/Fixture.cs");
        var options = new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary)
            .WithNullableContextOptions(NullableContextOptions.Enable);
        if (configuredSeverity is not null)
        {
            options = options.WithSpecificDiagnosticOptions(
                new Dictionary<string, ReportDiagnostic>
                {
                    [diagnosticId] = configuredSeverity.Value,
                });
        }

        var references = TrustedPlatformReferences(includeTestFramework).ToList();
        var visited = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        if (includeEntityFramework)
        {
            AddAssemblyAndDependencies(typeof(DbContext).Assembly, references, visited);
        }

        if (includeRelational || includeSqlServer || includeNpgsql || includeMySql)
        {
            AddAssemblyAndDependencies(typeof(ModelSnapshot).Assembly, references, visited);
        }

        if (includeSqlServer)
        {
            AddAssemblyAndDependencies(typeof(SqlServerDbContextOptionsExtensions).Assembly, references, visited);
        }

        if (includeNpgsql)
        {
            AddAssemblyAndDependencies(typeof(NpgsqlDbContextOptionsBuilderExtensions).Assembly, references, visited);
        }

        if (includeMySql)
        {
            AddAssemblyAndDependencies(typeof(MySqlDbContextOptionsBuilderExtensions).Assembly, references, visited);
        }

        return CSharpCompilation.Create(
            "AnalyzerFixture",
            [syntaxTree],
            references,
            options);
    }

    private static void AddAssemblyAndDependencies(
        Assembly assembly,
        ICollection<MetadataReference> references,
        ISet<string> visited)
    {
        if (assembly.IsDynamic || string.IsNullOrEmpty(assembly.Location) || !visited.Add(assembly.FullName!))
        {
            return;
        }

        references.Add(MetadataReference.CreateFromFile(assembly.Location));
        foreach (var name in assembly.GetReferencedAssemblies())
        {
            try
            {
                AddAssemblyAndDependencies(Assembly.Load(name), references, visited);
            }
            catch (FileNotFoundException)
            {
                // A compilation only needs the dependencies reachable in the local test runtime.
            }
        }
    }
}
